// Milestone 3 check: generate from the welcome screen through the real server + model. Usage: pnpm dev, then node scripts/generate-e2e.mjs [outDir]
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { launch } from "./browser.mjs";

const BASE = process.env.APP_URL ?? "http://localhost:5173";
const out = resolve(process.argv[2] ?? "screenshots");
mkdirSync(out, { recursive: true });
const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(BASE);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.getByText(/Local AI ready/).waitFor({ timeout: 10000 });
await page.screenshot({ path: `${out}/gen-welcome.png` });
await page.getByLabel("Describe an animation").fill("a fox sleeping on a cushion by an autumn window at dusk, wind picks up at 5s");
await page.getByRole("button", { name: "Generate with AI" }).click();
const t0 = Date.now();
await page.waitForFunction(() => window.studio.getState().spec?.beats.length > 0, null, { timeout: 120000 });
console.log(`storyboard beats on timeline after ${((Date.now() - t0) / 1000).toFixed(0)}s:`, await page.evaluate(() => window.studio.getState().spec.beats.map((b) => `${b.at}s ${b.label}`).join(" | ")));
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}/gen-progress.png` });
await page.waitForFunction(() => ["done", "error"].includes(window.studio.getState().generation?.status), null, { timeout: 600000 });
const s = await page.evaluate(() => { const st = window.studio.getState(); return { status: st.generation.status, message: st.generation.message, layers: st.spec.layers.map((l) => l.type), playing: st.playing, chat: st.chat.map((m) => m.text) }; });
console.log(`finished after ${((Date.now() - t0) / 1000).toFixed(0)}s:`, JSON.stringify(s));
console.log("timeline rows with AI spark:", await page.locator('[aria-label="Made by AI"]').count());
await page.waitForTimeout(1500);
console.log("time advanced while playing:", await page.evaluate(() => window.studio.getState().t.toFixed(2)));
await page.screenshot({ path: `${out}/gen-done.png` });
await browser.close();
console.log(errors.length ? `page errors:\n${errors.join("\n")}` : "no page errors");
